// Downloads the variable woff2 files for the two brand fonts (Newsreader for reading,
// Schibsted Grotesk for numbers, labels and UI) from Google Fonts and emits
// src/styles/fonts.css with self-hosted @font-face rules (stable /fonts/ URLs).
// Latin plus latin-ext, so the rupee sign (U+20B9, in latin-ext) comes from the same
// typeface as the digits beside it. Run once: `node scripts/fetch-fonts.mjs`.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FONTS = join(ROOT, "public", "fonts");
const OUT_CSS = join(ROOT, "src", "styles", "fonts.css");
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const families = [
  "Newsreader:ital,opsz,wght@0,6..72,300..700;1,6..72,300..700",
  "Schibsted+Grotesk:ital,wght@0,400..800;1,400..800"
];

await mkdir(OUT_FONTS, { recursive: true });

let css = "/* Self-hosted brand fonts: Newsreader (reading) and Schibsted Grotesk (numbers, labels, UI). Generated by scripts/fetch-fonts.mjs. */\n";
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

for (const fam of families) {
  const url = `https://fonts.googleapis.com/css2?family=${fam}&display=swap`;
  const sheet = await fetch(url, { headers: { "User-Agent": UA } }).then((r) => r.text());
  // Google emits one @font-face per unicode-range subset, each preceded by a /* subset */ comment.
  const blocks = sheet.split("/*").map((b) => "/*" + b);
  for (const block of blocks) {
    const subset = block.match(/\/\*\s*([a-z0-9-]+)\s*\*\//i)?.[1];
    if (subset !== "latin" && subset !== "latin-ext") continue; // English site; ext carries ₹
    const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = block.match(/font-weight:\s*([\d ]+);/)?.[1].trim();
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1].trim();
    const style = block.match(/font-style:\s*(\w+)/)?.[1] || "normal";
    const src = block.match(/url\(([^)]+\.woff2)\)/)?.[1];
    if (!family || !weight || !src) continue;
    const name = `${slug(family)}-${subset}${style === "italic" ? "-italic" : ""}.woff2`;
    const buf = Buffer.from(await fetch(src, { headers: { "User-Agent": UA } }).then((r) => r.arrayBuffer()));
    await writeFile(join(OUT_FONTS, name), buf);
    css +=
      `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};` +
      `font-display:swap;src:url('/fonts/${name}') format('woff2');unicode-range:${range}}\n`;
    console.log("  saved", name, (buf.length / 1024).toFixed(1) + "KB");
  }
}

await writeFile(OUT_CSS, css);
console.log("wrote", OUT_CSS);
