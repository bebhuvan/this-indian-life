// Reads advance widths from the TrueType fonts the kit draws with and writes them as a
// compact table, so chart layout measures text exactly instead of estimating it.
// Usage: node scripts/kit/build-metrics.mjs
import { readFileSync, writeFileSync } from "node:fs";

const FONTS = {
  sans400: "src/assets/og-fonts/SchibstedGrotesk-400.ttf",
  sans600: "src/assets/og-fonts/SchibstedGrotesk-600.ttf",
};
// Every character a chart label is likely to need; anything else falls back to the average.
const CHARS =
  " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~" +
  "–—−→←↑↓·×÷±≈≤≥°₹€£…‘’“”•";

function tables(buf) {
  const n = buf.readUInt16BE(4);
  const out = {};
  for (let i = 0; i < n; i++) {
    const o = 12 + i * 16;
    out[buf.toString("ascii", o, o + 4)] = { offset: buf.readUInt32BE(o + 8), length: buf.readUInt32BE(o + 12) };
  }
  return out;
}

function cmap4(buf, base) {
  const n = buf.readUInt16BE(base + 2);
  let sub = -1;
  for (let i = 0; i < n; i++) {
    const r = base + 4 + i * 8;
    const pid = buf.readUInt16BE(r), eid = buf.readUInt16BE(r + 2);
    if (pid === 3 && (eid === 1 || eid === 10)) {
      const off = base + buf.readUInt32BE(r + 4);
      if (buf.readUInt16BE(off) === 4) { sub = off; break; }
    }
  }
  if (sub < 0) throw new Error("no format 4 cmap");
  const segX2 = buf.readUInt16BE(sub + 6), seg = segX2 / 2;
  const ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
  return (code) => {
    for (let i = 0; i < seg; i++) {
      const end = buf.readUInt16BE(ends + i * 2);
      if (code > end) continue;
      const start = buf.readUInt16BE(starts + i * 2);
      if (code < start) return 0;
      const delta = buf.readInt16BE(deltas + i * 2), ro = buf.readUInt16BE(ranges + i * 2);
      if (ro === 0) return (code + delta) & 0xffff;
      const g = buf.readUInt16BE(ranges + i * 2 + ro + (code - start) * 2);
      return g === 0 ? 0 : (g + delta) & 0xffff;
    }
    return 0;
  };
}

function widths(path) {
  const buf = readFileSync(path);
  const t = tables(buf);
  const upm = buf.readUInt16BE(t.head.offset + 18);
  const nH = buf.readUInt16BE(t.hhea.offset + 34);
  const glyph = cmap4(buf, t.cmap.offset);
  const adv = (g) => buf.readUInt16BE(t.hmtx.offset + Math.min(g, nH - 1) * 4);
  const map = {};
  let sum = 0, count = 0;
  for (const ch of CHARS) {
    const g = glyph(ch.codePointAt(0));
    if (!g) continue;
    const w = Math.round((adv(g) / upm) * 1000);
    map[ch] = w;
    if (/[a-z0-9]/.test(ch)) { sum += w; count++; }
  }
  // Tabular figures: the widest digit, which is what `font-variant-numeric: tabular-nums` sets.
  const tab = Math.max(...[..."0123456789"].map((d) => map[d]));
  return { avg: Math.round(sum / count), tab, map };
}

const out = Object.fromEntries(Object.entries(FONTS).map(([k, p]) => [k, widths(p)]));
writeFileSync(
  "src/kit/metrics.generated.ts",
  "// Generated by scripts/kit/build-metrics.mjs from the kit's font files. Advance widths in\n" +
    "// thousandths of an em. Do not edit by hand.\n" +
    `export const METRICS = ${JSON.stringify(out)} as const;\n`,
);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, { avg: v.avg, tab: v.tab, chars: Object.keys(v.map).length }])));
