// Kerning pairs for the kit's text measurement, measured in the browser from the same fonts
// build-metrics.mjs reads. The advance widths alone over-measured kerned labels by 1 to 4%
// ("Tertiary/post-secondary (16+)" by 7 px at 14 px), so right-aligned names started a few
// pixels in from the figure's edge. Writes src/kit/kerning.generated.ts.
//   INDICA_CHROME=/usr/bin/chromium INDICA_PUPPETEER_DIR=<dir with puppeteer-core> node scripts/kit/build-kerning.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const chrome = process.env.INDICA_CHROME;
if (!chrome) {
  console.error("Needs INDICA_CHROME (and INDICA_PUPPETEER_DIR if puppeteer-core is not installed here).");
  process.exit(2);
}
const base = process.env.INDICA_PUPPETEER_DIR ? join(process.env.INDICA_PUPPETEER_DIR, "noop.js") : import.meta.url;
const puppeteer = createRequire(base)("puppeteer-core");

const FONTS = { sans400: "src/assets/og-fonts/SchibstedGrotesk-400.ttf", sans600: "src/assets/og-fonts/SchibstedGrotesk-600.ttf" };
// The characters labels are made of. Pairs moving less than 20 units in 1000 (0.3 px at 14 px) are left out.
const CHARS = " ()+-/.,:%$₹0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
const MIN = 20;

const browser = await puppeteer.launch({ executablePath: chrome, headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage();
const out = {};
for (const [name, file] of Object.entries(FONTS)) {
  const b64 = readFileSync(file).toString("base64");
  out[name] = await page.evaluate(async (b64, chars, min) => {
    const face = new FontFace("K", `url(data:font/ttf;base64,${b64})`);
    await face.load();
    document.fonts.add(face);
    const c = document.createElement("canvas").getContext("2d");
    c.font = "1000px K";
    c.fontKerning = "normal";
    const w = (s) => c.measureText(s).width;
    const one = Object.fromEntries([...chars].map((ch) => [ch, w(ch)]));
    const pairs = {};
    for (const a of chars) for (const b of chars) {
      const k = Math.round(w(a + b) - one[a] - one[b]);
      if (Math.abs(k) >= min) pairs[a + b] = k;
    }
    document.fonts.delete(face);
    return pairs;
  }, b64, CHARS, MIN);
  console.log(name, Object.keys(out[name]).length, "pairs");
}
await browser.close();
writeFileSync(
  "src/kit/kerning.generated.ts",
  "// Generated by scripts/kit/build-kerning.mjs: kerning, in thousandths of an em, for pairs that move 2% or more.\n" +
    `export const KERNING: Record<"sans400" | "sans600", Record<string, number>> = ${JSON.stringify(out)};\n`,
);
